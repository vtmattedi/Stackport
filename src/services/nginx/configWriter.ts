const NGINX_LOG_FORMAT_NAME = "stackport";
// Extended combined format: adds "$host" and $request_time after the standard combined fields.
// Enables per-domain traffic breakdown and response-time percentiles in metrics.
// Defined at http level; referenced by access_log inside each server block (not at http level,
// which would double-log since nginx.conf already has an access_log directive there).
const NGINX_LOG_FORMAT_BLOCK = `log_format ${NGINX_LOG_FORMAT_NAME} '$remote_addr - $remote_user [$time_local] "$request" $status $body_bytes_sent "$http_referer" "$http_user_agent" "$host" $request_time';`;

