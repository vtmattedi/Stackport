export function getNginxAppConfig(): NginxAppConfig {
  const rows = getDatabase()
    .prepare("SELECT key, value FROM app_meta WHERE key IN (?, ?, ?)")
    .all(APP_NGINX_ENABLED_KEY, APP_NGINX_DOMAIN_KEY, APP_NGINX_USE_SSL_KEY) as Array<{ key: string; value: string }>;
  const values = new Map(rows.map((row) => [row.key, row.value]));
  return {
    enabled: values.get(APP_NGINX_ENABLED_KEY) === "1",
    domain: values.get(APP_NGINX_DOMAIN_KEY) ?? "",
    port: config.port,
    useSsl: values.get(APP_NGINX_USE_SSL_KEY) !== "0",
  };
}

export function setNginxAppConfig(input: { enabled: boolean; domain: string; useSsl?: boolean }): NginxAppConfig {
  const domain = input.domain.trim().toLowerCase();
  if (input.enabled && !DOMAIN_RE.test(domain)) {
    throw new Error("domain must be a valid hostname before enabling app Nginx publishing");
  }

  const db = getDatabase();
  if (input.enabled) {
    const portConflict = db.prepare("SELECT name FROM projects WHERE internal_port = ? LIMIT 1").get(config.port) as { name: string } | undefined;
    if (portConflict) {
      throw new Error(`Cannot enable app Nginx publishing because project "${portConflict.name}" already uses backend port ${config.port}`);
    }
    const domainConflict = db.prepare(
      "SELECT p.name AS name FROM project_domains pd JOIN projects p ON p.id = pd.project_id WHERE lower(pd.domain) = lower(?) LIMIT 1"
    ).get(domain) as { name: string } | undefined;
    if (domainConflict) {
      throw new Error(`Cannot enable app Nginx publishing because project "${domainConflict.name}" already uses ${domain}`);
    }
  }

  const now = new Date().toISOString();
  const upsert = db.prepare(`
    INSERT INTO app_meta (key, value, updated_at) VALUES (?, ?, ?)
    ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at
  `);
  upsert.run(APP_NGINX_ENABLED_KEY, input.enabled ? "1" : "0", now);
  upsert.run(APP_NGINX_DOMAIN_KEY, domain, now);
  upsert.run(APP_NGINX_USE_SSL_KEY, input.useSsl === false ? "0" : "1", now);

  return getNginxAppConfig();
}

// The compose *service* name StackPort's own container runs as in docker-compose.
// system.yml (not container_name — Docker DNS over a shared network resolves by
// service name). Reachable from stackport-nginx once both join stackport-proxy.
const STACKPORT_APP_SERVICE = "stackport";

function appRouteTarget(appConfig: NginxAppConfig = getNginxAppConfig()): NginxTarget | null {
  if (!appConfig.enabled || !appConfig.domain) return null;
  return {
    name: APP_ROUTE_NAME,
    domain: appConfig.domain,
    service: STACKPORT_APP_SERVICE,
    containerPort: appConfig.port,
    useSsl: appConfig.useSsl,
    includeWwwRedirect: false,
    extraConfig: "",
    extraBlocks: "",
  };
}

/** One NginxTarget per routed (project, domain) pair — each domain gets its own full
 *  block set (server_name/cert/www-redirect), routing to whichever service/port that
 *  specific domain is configured for (Phase 1.7 — domain -> service -> container_port,
 *  no longer one shared internalPort per project). A domain with no service/port
 *  configured yet is skipped entirely — nothing to route to. includeWwwRedirect's
 *  apex check runs across every routed domain from every project, same as before —
 *  it was already domain-string-based, not project-based. */
function projectRouteTargets(projects: Project[], domainsByProject: Map<number, ProjectDomain[]>): NginxTarget[] {
  const isRouted = (pd: ProjectDomain): pd is ProjectDomain & { containerPort: number } => !!pd.service && !!pd.containerPort;
  const allDomains = projects.flatMap((project) => (domainsByProject.get(project.id) ?? []).filter(isRouted).map((pd) => pd.domain));
  const apexDomains = new Set(splitDomainLists(allDomains).domainList);

  return projects.flatMap((project) =>
    (domainsByProject.get(project.id) ?? []).filter(isRouted).map((pd) => ({
      name: project.name,
      domain: pd.domain,
      service: pd.service,
      containerPort: pd.containerPort,
      useSsl: pd.useSsl,
      includeWwwRedirect: apexDomains.has(pd.domain) && !allDomains.includes(`www.${pd.domain}`),
      extraConfig: project.nginxExtraConfig ?? "",
      extraBlocks: project.nginxExtraBlocks ?? "",
    }))
  );
}

async function routeTargets(projects: Project[]): Promise<NginxTarget[]> {
  const appTarget = appRouteTarget();
  const domainsByProject = listAllRoutableProjectDomains();
  return [...(appTarget ? [appTarget] : []), ...projectRouteTargets(projects, domainsByProject)];
}

function splitDomainLists(domains: string[]): { domainList: string[]; subdomainList: string[] } {
  const domainSet = new Set(domains);
  const subdomainList: string[] = [];
  const domainList: string[] = [];

  for (const domain of domains) {
    const parts = domain.split(".");
    const hasProjectParent = parts.some((_part, index) => {
      if (index === 0) return false;
      return domainSet.has(parts.slice(index).join("."));
    });

    if (hasProjectParent) {
      subdomainList.push(domain);
    } else {
      domainList.push(domain);
    }
  }

  return { domainList, subdomainList };
}

function listComment(label: string, values: string[]): string {
  const items = values.length > 0 ? values.map((value) => `# - ${value}`).join("\n") : "# - none";
  return `# ${label}:\n${items}`;
}

export async function generateNginxConfig(projects: Project[]): Promise<string> {
  await ensureTemplates();
  const p = paths();
  const [generalTemplate, projectTemplate, targets, selfSignedReady] = await Promise.all([
    fs.readFile(p.generalTemplate, "utf8"),
    fs.readFile(p.projectTemplate, "utf8"),
    routeTargets(projects),
    Promise.all([fileExists(SELF_SIGNED_CERT_PATH), fileExists(SELF_SIGNED_KEY_PATH)]).then(([cert, key]) => cert && key),
  ]);
  const allDomains = targets.map((target) => target.domain).sort((a, b) => a.localeCompare(b));
  const lists = splitDomainLists(allDomains);
  // App domain not configured yet + a self-signed cert exists (Phase 1.9 bootstrap,
  // services/appIngress.ts) -> serve the app itself as the HTTPS default_server so
  // first login works over a raw IP. Once a real app domain is set, appRouteTarget()
  // already produces its own domain-matched block and this reverts to rejecting
  // unmatched hosts, same as before Phase 1.9.
  const appConfigured = !!getNginxAppConfig().domain;
  const httpsDefaultServerBlock = !appConfigured && selfSignedReady
    ? selfSignedDefaultServerBlock()
    : REJECT_UNKNOWN_TLS_BLOCK;
  const generalBlock = generalTemplate
    .replace(/\{\{domainList\}\}/g, listComment("Domains", lists.domainList))
    .replace(/\{\{subdomainList\}\}/g, listComment("Subdomains", lists.subdomainList))
    .replace(/\{\{allDomainList\}\}/g, listComment("All routed domains", allDomains))
    .replace(/\{\{httpsDefaultServerBlock\}\}/g, httpsDefaultServerBlock);
  const blocks = (await Promise.all(targets.map((target) => renderDomainBlock(projectTemplate, target))))
    .map((block) => block.trimEnd())
    .join("\n\n");

  return [generalBlock.trimEnd(), blocks.trimEnd()].filter(Boolean).join("\n\n") + "\n";
}

async function run(cmd: string, args: string[], timeoutMs = 12_000): Promise<RunResult> {
  return new Promise((resolve) => {
    execFile(cmd, args, { timeout: timeoutMs, maxBuffer: 4 * 1024 * 1024 }, (err, stdout, stderr) => {
      const notFound = !!(err && (err as NodeJS.ErrnoException).code === "ENOENT");
      resolve({ stdout, stderr, ok: !err, notFound });
    });
  });
}

function privileged(cmd: string, args: string[]): { cmd: string; args: string[] } {
  if (typeof process.getuid === "function" && process.getuid() === 0) {
    return { cmd, args };
  }
  return { cmd: "sudo", args: ["-n", cmd, ...args] };
}

/** Wraps an already-built nginx CLI invocation for either runtime: "host" runs it
 *  (possibly sudo-wrapped) directly against the host's own nginx/systemctl, exactly
 *  as before; "container" runs the identical nginx-side arguments through
 *  `docker exec` against stackport-nginx instead — using the docker.sock access
 *  StackPort's own container already has, not sudo. */
function nginxCommand(cmd: string, args: string[]): { cmd: string; args: string[] } {
  if (getNginxRuntime() === "container") {
    return { cmd: "docker", args: ["exec", NGINX_CONTAINER_NAME, cmd, ...args] };
  }
  return privileged(cmd, args);
}

async function validateCurrentFile(): Promise<RunResult> {
  const command = nginxCommand("nginx", ["-t"]);
  return run(command.cmd, command.args);
}

async function validateCandidateFile(candidatePath: string): Promise<RunResult> {
  const p = paths();
  const tempMain = path.join(p.backupDir, `candidate.${Date.now()}.nginx.conf`);
  const mimeTypes = (await fileExists(path.join(p.root, "mime.types")))
    ? path.join(p.root, "mime.types")
    : "/etc/nginx/mime.types";
  const includeMimeTypes = await fileExists(mimeTypes) ? `    include ${mimeTypes};\n` : "";
  const tempConfig = `events {}

http {
${includeMimeTypes}    include ${candidatePath};
}
`;

  await fs.mkdir(p.backupDir, { recursive: true });
  await fs.writeFile(tempMain, tempConfig, "utf8");
  const command = nginxCommand("nginx", ["-t", "-c", tempMain]);
  const result = await run(command.cmd, command.args);
  await fs.rm(tempMain, { force: true }).catch(() => undefined);
  return result;
}

async function restartNginx(): Promise<RunResult> {
  // Reload itself isn't just a differently-wrapped version of the same command here
  // (unlike validate, above) — the container has no systemd/systemctl at all, so
  // "container" mode reloads nginx directly via its own `-s reload` instead.
  const command = getNginxRuntime() === "container"
    ? { cmd: "docker", args: ["exec", NGINX_CONTAINER_NAME, "nginx", "-s", "reload"] }
    : privileged("systemctl", ["reload", "nginx"]);
  return run(command.cmd, command.args);
}

async function readState(): Promise<NginxState | null> {
  try {
    return JSON.parse(await fs.readFile(paths().state, "utf8")) as NginxState;
  } catch {
    return null;
  }
}

async function writeState(result: NginxApplyResult): Promise<void> {
  const previous = await readState();
  const state: NginxState = {
    ...result,
    updatedAt: new Date().toISOString(),
    restartCount: result.ok ? (previous?.restartCount ?? 0) + 1 : (previous?.restartCount ?? 0),
  };
  await fs.mkdir(path.dirname(paths().state), { recursive: true });
  await fs.writeFile(paths().state, JSON.stringify(state, null, 2) + "\n", "utf8");
}

async function backupCurrentFile(): Promise<string | null> {
  const p = paths();
  if (!(await fileExists(p.target))) return null;

  await fs.mkdir(p.backupDir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const backupPath = path.join(p.backupDir, `default.${stamp}.bak`);
  await fs.copyFile(p.target, backupPath);
  return backupPath;
}

async function restoreBackup(backupPath: string | null): Promise<boolean> {
  if (!backupPath) {
    await fs.rm(paths().target, { force: true });
    return true;
  }
  await fs.copyFile(backupPath, paths().target);
  return true;
}

/** Single choke point for every nginx config mutation in the app (project/domain
 *  changes, manual Apply/Reload, certbot actions, MCP tools) — invalidates the
 *  cached "active" status once per apply attempt, regardless of outcome, since a
 *  reload can flip active/inactive either way. */
export async function writeNginxConfig(): Promise<NginxApplyResult> {
  const result = await writeNginxConfigImpl();
  invalidateNginxActiveStatus();
  return result;
}

async function writeNginxConfigImpl(): Promise<NginxApplyResult> {
  const p = paths();
  const projects = await loadProjects();
  const content = await generateNginxConfig(projects);
  const candidatePath = path.join(p.backupDir, `candidate.${Date.now()}.conf`);

  await fs.mkdir(path.dirname(p.target), { recursive: true });
  await fs.mkdir(p.backupDir, { recursive: true });
  await fs.writeFile(candidatePath, content, "utf8");

  const validation = await validateCandidateFile(candidatePath);
  const validationOutput = (validation.stderr || validation.stdout).trim();
  if (!validation.ok) {
    await fs.copyFile(candidatePath, p.failedConfig).catch(() => undefined);
    await fs.rm(candidatePath, { force: true }).catch(() => undefined);
    const result: NginxApplyResult = {
      ok: false,
      mode: "real",
      targetPath: p.target,
      backupPath: null,
      restored: false,
      output: validationOutput || "nginx validation failed",
    };
    await writeState(result);
    return result;
  }

  const backupPath = await backupCurrentFile();
  await fs.copyFile(candidatePath, p.target);
  await fs.rm(candidatePath, { force: true }).catch(() => undefined);

  const currentValidation = await validateCurrentFile();
  const currentValidationOutput = (currentValidation.stderr || currentValidation.stdout).trim();
  if (!currentValidation.ok) {
    await fs.writeFile(p.failedConfig, content, "utf8").catch(() => undefined);
    await restoreBackup(backupPath);
    const result: NginxApplyResult = {
      ok: false,
      mode: "real",
      targetPath: p.target,
      backupPath,
      restored: true,
      output: currentValidationOutput || "nginx validation failed after replacing config",
    };
    await writeState(result);
    return result;
  }

  const restart = await restartNginx();
  const restartOutput = (restart.stderr || restart.stdout).trim();
  if (!restart.ok) {
    await fs.writeFile(p.failedConfig, content, "utf8").catch(() => undefined);
    await restoreBackup(backupPath);
    const result: NginxApplyResult = {
      ok: false,
      mode: "real",
      targetPath: p.target,
      backupPath,
      restored: true,
      output: [currentValidationOutput, restartOutput || "nginx reload failed"].filter(Boolean).join("\n"),
    };
    await writeState(result);
    return result;
  }

  await fs.rm(p.failedConfig, { force: true }).catch(() => undefined);
  const result: NginxApplyResult = {
    ok: true,
    mode: "real",
    targetPath: p.target,
    backupPath,
    restored: false,
    output: [currentValidationOutput, restartOutput].filter(Boolean).join("\n"),
  };
  await writeState(result);
  return result;
}

export async function testNginxConfig(): Promise<{ ok: boolean; output: string }> {
  await ensureTemplates().catch(() => undefined);
  if (!(await fileExists(paths().target))) {
    return { ok: false, output: `No generated config found at ${paths().target}` };
  }
  const result = await validateCurrentFile();
  return { ok: result.ok, output: (result.stderr || result.stdout).trim() };
}

export async function reloadNginx(): Promise<NginxApplyResult> {
  return writeNginxConfig();
}

export async function getNginxLayerStatus(): Promise<NginxLayerStatus> {
  await ensureTemplates().catch(() => undefined);
  const p = paths();
  const [exists, failedConfigExists, projects, lastOperation] = await Promise.all([
    fileExists(p.target),
    fileExists(p.failedConfig),
    loadProjects(),
    readState(),
  ]);

  let sizeBytes: number | null = null;
  if (exists) {
    sizeBytes = (await fs.stat(p.target)).size;
  }

  let backupCount = 0;
  try {
    backupCount = (await fs.readdir(p.backupDir)).filter((name) => name.endsWith(".bak")).length;
  } catch {
    backupCount = 0;
  }

  const app = getNginxAppConfig();
  const targets = await routeTargets(projects);
  const domains = targets.map((target) => target.domain).sort((a, b) => a.localeCompare(b));
  const lists = splitDomainLists(domains);
  const routes = targets
    .map((target) => ({ project: target.name, domain: target.domain, service: target.service, port: target.containerPort }))
    .sort((a, b) => a.domain.localeCompare(b.domain));

  return {
    mode: "real",
    rootPath: p.root,
    targetPath: p.target,
    generalTemplatePath: p.generalTemplate,
    projectTemplatePath: p.projectTemplate,
    backupDir: p.backupDir,
    exists,
    failedConfigExists,
    sizeBytes,
    domains,
    domainList: lists.domainList,
    subdomainList: lists.subdomainList,
    routes,
    backupCount,
    lastOperation,
    app,
    fixedBlockPath: p.generalTemplate,
    domainTemplatePath: p.projectTemplate,
  };
}

export async function readNginxDocument(kind: NginxDocumentKind): Promise<NginxDocument> {
  if (kind !== "generated" && kind !== "failed") await ensureTemplates().catch(() => undefined);
  const filePath = documentPath(kind);
  const exists = await fileExists(filePath);

  if (!exists) {
    return {
      kind,
      path: filePath,
      editable: kind !== "generated" && kind !== "failed",
      content: "",
      updatedAt: null,
      sizeBytes: null,
    };
  }

  const [content, stat] = await Promise.all([
    fs.readFile(filePath, "utf8"),
    fs.stat(filePath),
  ]);

  return {
    kind,
    path: filePath,
    editable: kind !== "generated" && kind !== "failed",
    content,
    updatedAt: stat.mtime.toISOString(),
    sizeBytes: stat.size,
  };
}

export async function writeNginxTemplate(kind: Exclude<NginxDocumentKind, "generated">, content: string): Promise<NginxDocument> {
  await ensureTemplates();
  const filePath = documentPath(kind);
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, "utf8");
  return readNginxDocument(kind);
}
