function resolveRoot(): string {
  return path.resolve(config.nginxPath);
}

function paths() {
  const root = resolveRoot();
  return {
    root,
    target: path.join(root, DEFAULT_SITE),
    generalTemplate: path.join(root, TEMPLATE_DIR, "general.conf"),
    projectTemplate: path.join(root, TEMPLATE_DIR, "project.conf"),
    fixedBlock: path.join(root, TEMPLATE_DIR, "fixed.conf"),
    domainTemplate: path.join(root, TEMPLATE_DIR, "domain.conf"),
    backupDir: path.join(root, BACKUP_DIR),
    state: path.join(root, STATE_FILE),
    failedConfig: path.join(root, FAILED_FILE),
  };
}

function documentPath(kind: NginxDocumentKind): string {
  const p = paths();
  if (kind === "generated") return p.target;
  if (kind === "failed") return p.failedConfig;
  if (kind === "general") return p.generalTemplate;
  return p.projectTemplate;
}

async function fileExists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function ensureTemplates(): Promise<void> {
  const p = paths();
  await fs.mkdir(path.dirname(p.generalTemplate), { recursive: true });
  if (!(await fileExists(p.generalTemplate))) {
    await fs.writeFile(p.generalTemplate, DEFAULT_GENERAL_TEMPLATE + "\n", "utf8");
  } else {
    let existing = await fs.readFile(p.generalTemplate, "utf8");
    let migrated = false;
    // Upgrade: prepend log_format block if the template predates this feature
    if (!existing.includes(`log_format ${NGINX_LOG_FORMAT_NAME}`)) {
      existing = NGINX_LOG_FORMAT_BLOCK + "\n\n" + existing;
      migrated = true;
    }
    // Upgrade: replace the old hardcoded reject-unknown-TLS block with the
    // {{httpsDefaultServerBlock}} placeholder (Phase 1.9 — self-signed bootstrap
    // support needs this to be dynamic, see generateNginxConfig()).
    if (!existing.includes("{{httpsDefaultServerBlock}}") && existing.includes(REJECT_UNKNOWN_TLS_BLOCK)) {
      existing = existing.replace(REJECT_UNKNOWN_TLS_BLOCK, "{{httpsDefaultServerBlock}}");
      migrated = true;
    }
    if (migrated) {
      await fs.writeFile(p.generalTemplate, existing, "utf8");
    }
  }
  if (!(await fileExists(p.projectTemplate))) {
    await fs.writeFile(p.projectTemplate, DEFAULT_PROJECT_TEMPLATE + "\n", "utf8");
  } else {
    const existing = await fs.readFile(p.projectTemplate, "utf8");
    if (existing.trim() === LEGACY_PROJECT_TEMPLATE.trim() || existing.trim() === PREVIOUS_DEFAULT_PROJECT_TEMPLATE.trim()) {
      await fs.writeFile(p.projectTemplate, DEFAULT_PROJECT_TEMPLATE + "\n", "utf8");
    }
  }
}

/** Indents each non-empty line of a raw directive block to match the location body (8 spaces). */
function indentExtraConfig(extraConfig: string): string {
  const lines = extraConfig.split("\n").map((line) => line.trim()).filter(Boolean);
  if (lines.length === 0) return "";
  return "\n" + lines.map((line) => `        ${line}`).join("\n");
}

/**
 * Re-indents a raw block of nginx config (e.g. one or more `location { ... }` blocks) to the
 * server body level (4 spaces), preserving the relative nesting the user typed by dedenting to
 * the shallowest line first. Unlike indentExtraConfig, this content isn't flattened to one
 * level — it may contain its own `{ }` nesting.
 */
function indentExtraBlocks(extraBlocks: string): string {
  const rawLines = extraBlocks.replace(/\r\n/g, "\n").split("\n");
  const nonEmpty = rawLines.filter((line) => line.trim().length > 0);
  if (nonEmpty.length === 0) return "";
  const minIndent = Math.min(...nonEmpty.map((line) => line.match(/^ */)?.[0].length ?? 0));
  return "\n\n" + nonEmpty.map((line) => `    ${line.slice(minIndent)}`).join("\n");
}

/** Substitutes project template vars (currently just `{{PORT}}`) into a project's raw extraBlocks, then indents it for embedding in the HTTPS server block. */
function renderExtraBlocks(target: NginxTarget): string {
  if (!target.extraBlocks.trim()) return "";
  const substituted = target.extraBlocks.replace(/\{\{PORT\}\}/g, String(target.containerPort));
  return indentExtraBlocks(substituted);
}

function locationBlock(target: NginxTarget): string {
  const upstreamUrl = `http://${target.service}:${target.containerPort}`;
  // Resolve at request time so a stopped/not-yet-deployed workload cannot prevent
  // nginx from loading Stackport's own admin route. Also refresh DNS after recreation.
  const proxy = getNginxRuntime() === "container"
    ? `resolver 127.0.0.11 valid=10s ipv6=off;\n        set $stackport_upstream ${upstreamUrl};\n        proxy_pass $stackport_upstream;`
    : `proxy_pass ${upstreamUrl};`;

  return `
    location / {
        ${proxy}
        proxy_http_version 1.1;

        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";

        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;${indentExtraConfig(target.extraConfig)}
    }`;
}

async function certificateExists(domain: string): Promise<boolean> {
  const certBase = path.join("/etc/letsencrypt/live", domain);
  const files = [path.join(certBase, "fullchain.pem"), path.join(certBase, "privkey.pem")];

  if (getNginxRuntime() === "container") {
    const checks = await Promise.all(files.map((file) => run("docker", ["exec", NGINX_CONTAINER_NAME, "test", "-f", file])));
    return checks.every((check) => check.ok);
  }

  const direct = await Promise.all(files.map((file) => fileExists(file)));
  if (direct.every(Boolean)) return true;

  const checks = await Promise.all(files.map((file) => {
    const command = privileged("test", ["-f", file]);
    return run(command.cmd, command.args);
  }));
  return checks.every((check) => check.ok);
}

// `^~` gives this prefix match priority over both `location /`'s proxy and the plain
// Redirects belong inside `location /` so server-level rewrite processing cannot
// intercept ACME HTTP-01 challenges during issuance or renewal.
function acmeChallengeLocation(): string {
  return `
    location ^~ /.well-known/acme-challenge/ {
        root ${CERTBOT_WEBROOT_PATH};
        default_type "text/plain";
    }`;
}

function httpServerBlock(target: NginxTarget, hasCertificate: boolean): string {
  const domain = target.domain;
  const body = hasCertificate
    ? `    location / {\n        return 301 https://${domain}$request_uri;\n    }`
    : `    access_log /var/log/nginx/access.log ${NGINX_LOG_FORMAT_NAME};\n${locationBlock(target).replace(/^\n/, "").trimEnd()}`;

  return `server {
    listen 80;
    listen [::]:80;

    server_name ${domain};
${acmeChallengeLocation()}

${body}
}`;
}

function wwwDomain(target: NginxTarget): string | null {
  if (!target.includeWwwRedirect || target.domain.startsWith("www.")) return null;
  return `www.${target.domain}`;
}

function wwwHttpRedirectBlock(target: NginxTarget, hasCertificate: boolean): string {
  const www = wwwDomain(target);
  if (!www) return "";
  const scheme = hasCertificate ? "https" : "http";

  return `server {
    listen 80;
    listen [::]:80;

    server_name ${www};
${acmeChallengeLocation()}
    location / {
        return 301 ${scheme}://${target.domain}$request_uri;
    }
}`;
}

// Phase 1.9 — the very first login on a domain-less (raw-IP) install has to happen
// over HTTPS with no real domain and no Let's Encrypt cert yet possible (LE doesn't
// issue for bare IPs). Renders the app itself as the HTTPS default_server, using the
// self-signed cert services/nginx/selfSignedCert.ts generates once at boot. Reuses
// locationBlock() exactly like appRouteTarget()'s normal domain-matched block does —
// only the listen/server_name/cert lines differ (default_server + server_name "_"
// instead of a real hostname, self-signed paths instead of a letsencrypt/live one).
function selfSignedDefaultServerBlock(): string {
  const target: NginxTarget = {
    name: APP_ROUTE_NAME,
    domain: "_",
    service: STACKPORT_APP_SERVICE,
    containerPort: config.port,
    useSsl: true,
    includeWwwRedirect: false,
    extraConfig: "",
    extraBlocks: "",
  };

  return `# HTTPS fallback: no app domain configured yet — serve StackPort itself over
# the self-signed bootstrap certificate so first login is still HTTPS. Superseded
# automatically once a real app domain is configured (see appRouteTarget()).
server {
    listen 443 ssl http2 default_server;
    listen [::]:443 ssl http2 default_server;

    server_name _;

    ssl_certificate ${SELF_SIGNED_CERT_PATH};
    ssl_certificate_key ${SELF_SIGNED_KEY_PATH};

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;

    access_log /var/log/nginx/access.log ${NGINX_LOG_FORMAT_NAME};
${locationBlock(target)}
}`;
}

function httpsServerBlock(target: NginxTarget): string {
  const domain = target.domain;
  const certBase = `/etc/letsencrypt/live/${domain}`;

  return `server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;

    server_name ${domain};

    ssl_certificate ${certBase}/fullchain.pem;
    ssl_certificate_key ${certBase}/privkey.pem;

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;

    access_log /var/log/nginx/access.log ${NGINX_LOG_FORMAT_NAME};
${locationBlock(target)}${renderExtraBlocks(target)}
}`;
}

function wwwHttpsRedirectBlock(target: NginxTarget): string {
  const www = wwwDomain(target);
  if (!www) return "";
  const certBase = `/etc/letsencrypt/live/${target.domain}`;

  return `server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;

    server_name ${www};

    ssl_certificate ${certBase}/fullchain.pem;
    ssl_certificate_key ${certBase}/privkey.pem;

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;

    return 301 https://${target.domain}$request_uri;
}`;
}

async function renderDomainBlock(template: string, target: NginxTarget): Promise<string> {
  const domain = target.domain;
  const hasCertificate = target.useSsl && domain ? await certificateExists(domain) : false;
  const wwwRedirect = target.includeWwwRedirect ? wwwDomain(target) ?? "" : "";
  const upstreamUrl = `http://${target.service}:${target.containerPort}`;
  const values: Record<string, string> = {
    name: target.name,
    domain,
    wwwDomain: wwwRedirect,
    service: target.service,
    containerPort: String(target.containerPort),
    upstreamUrl,
    url: upstreamUrl,
    certBase: `/etc/letsencrypt/live/${domain}`,
    locationBlock: locationBlock(target),
    wwwHttpRedirectBlock: wwwHttpRedirectBlock(target, hasCertificate),
    httpServerBlock: httpServerBlock(target, hasCertificate),
    httpsServerBlock: hasCertificate ? httpsServerBlock(target) : "",
    wwwHttpsRedirectBlock: hasCertificate ? wwwHttpsRedirectBlock(target) : "",
    hasCertificate: hasCertificate ? "true" : "false",
    includeWwwRedirect: target.includeWwwRedirect ? "true" : "false",
  };

  return template.replace(/\{\{(name|domain|wwwDomain|service|containerPort|upstreamUrl|url|certBase|locationBlock|wwwHttpRedirectBlock|httpServerBlock|httpsServerBlock|wwwHttpsRedirectBlock|hasCertificate|includeWwwRedirect)\}\}/g, (_match, key: string) => values[key] ?? "");
}

